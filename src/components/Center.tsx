function DiagramView({ a }: { a: ProjectAnalysis }) {
  const code = useMemo(() => buildMermaid(a), [a]);
  const [svg, setSvg] = useState<string | null>(null);
  const [err, setErr] = useState<string | null>(null);
  const [copied, setCopied] = useState(false);

  useEffect(() => {
    let alive = true;
    // Mermaid is ~700 KB, so it is loaded lazily only when this tab opens.
    (async () => {
      try {
        const m = (await import("mermaid")).default;
        m.initialize({
          startOnLoad: false,
          theme: "dark",
          securityLevel: "strict",
          fontFamily: "Inter, system-ui, sans-serif",
          themeVariables: {
            primaryColor: "#1C1A10",
            primaryTextColor: "#E8C15A",
            primaryBorderColor: "#D4AF37",
            lineColor: "#D4AF37",
            secondaryColor: "#101820",
            tertiaryColor: "#0F1A12",
            background: "#0A0A0F",
            mainBkg: "#12121A",
            nodeBorder: "#3A3A4C",
            clusterBkg: "#12121A",
            clusterBorder: "#3A3A4C",
          },
        });
        const { svg } = await m.render(`mmd-${a.id}`, code);
        if (alive) {
          setSvg(svg);
          setErr(null);
        }
      } catch (e) {
        if (alive) {
          setErr(e instanceof Error ? e.message : String(e));
          setSvg(null);
        }
      }
    })();
    return () => {
      alive = false;
    };
  }, [code, a.id]);

  const copy = async () => {
    try {
      await navigator.clipboard.writeText(code);
      setCopied(true);
      setTimeout(() => setCopied(false), 1500);
    } catch {
      /* clipboard unavailable */
    }
  };

  return (
    <div className="animate-fadeUp space-y-4">
      <Card className="overflow-hidden p-5">
        <SectionTitle
          icon={<Workflow size={14} />}
          title="Module relationship map"
          right={
            <div className="flex gap-2">
              <Btn size="sm" icon={copied ? <Check size={12} /> : <Copy size={12} />} onClick={copy}>
                {copied ? "Copied" : "Copy Mermaid"}
              </Btn>
              <Btn size="sm" icon={<FileText size={12} />} onClick={() => {
                const blob = new Blob([code], { type: "text/plain" });
                const url = URL.createObjectURL(blob);
                const el = document.createElement("a");
                el.href = url;
                el.download = `${a.name.replace(/[^\w.-]+/g, "_")}.mmd`;
                el.click();
                setTimeout(() => URL.revokeObjectURL(url), 3000);
              }}>
                Download .mmd
              </Btn>
            </div>
          }
        />
        <div className="rounded-xl border border-white/5 bg-ink-950/60 p-4">
          {err ? (
            <div className="space-y-3">
              <div className="rounded-lg border border-red-500/30 bg-red-500/10 px-3 py-2 text-[12px] text-red-200">
                Mermaid failed to render: {err}
              </div>
              <pre className="overflow-x-auto rounded-lg bg-ink-950 p-3 font-mono text-[11px] text-zinc-400">{code}</pre>
            </div>
          ) : svg ? (
            <div className="flex justify-center overflow-x-auto" dangerouslySetInnerHTML={{ __html: svg }} />
          ) : (
            <div className="flex items-center justify-center py-16 text-zinc-500">
              <Loader2 size={20} className="animate-spin text-gold-400" />
            </div>
          )}
        </div>
        <p className="mt-3 text-[11px] leading-relaxed text-zinc-600">
          Edges are inferred from folder naming conventions (e.g. <code className="text-zinc-400">api → models</code>),
          not from import analysis. Use it as an orientation aid, then ask the assistant for specifics.
        </p>
      </Card>
    </div>
  );
}

