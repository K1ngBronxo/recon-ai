// File detail
// ---------------------------------------------------------------------------

function FileDetailView({
  a,
  path,
  readFile,
  onAskFile,
}: {
  a: ProjectAnalysis;
  path: string;
  readFile: (p: string) => Promise<string | null>;
  onAskFile: (path: string, content: string, explain?: boolean) => void;
}) {
  const [content, setContent] = useState<string | null>(null);
  const [loading, setLoading] = useState(true);
  const node = useMemo(() => {
    const walk = (nodes: typeof a.tree): (typeof a.tree)[number] | undefined => {
      for (const n of nodes) {
        if (n.path === path) return n;
        const hit = walk(n.children);
        if (hit) return hit;
      }
      return undefined;
    };
    return walk(a.tree);
  }, [a.tree, path]);

  useEffect(() => {
    let alive = true;
    setLoading(true);
    setContent(null);
    readFile(path).then((t) => {
      if (!alive) return;
      setContent(t);
      setLoading(false);
    });
    return () => {
      alive = false;
    };
  }, [path, readFile]);

  return (
    <div className="animate-fadeUp space-y-4">
      <Card className="p-5">
        <div className="flex flex-wrap items-center justify-between gap-3">
          <div className="min-w-0">
            <div className="flex items-center gap-2">
              <FileText size={15} className="shrink-0 text-gold-400" />
              <span className="truncate font-mono text-[14px] font-medium text-zinc-100">{path}</span>
            </div>
            <div className="mt-1.5 flex items-center gap-2">
              {node && <Badge>{node.size ? fmtBytes(node.size) : "—"}</Badge>}
              <Badge tone="blue">file</Badge>
            </div>
          </div>
          <div className="flex gap-2">
            <Btn variant="primary" icon={<Zap size={14} />} onClick={() => content !== null && onAskFile(path, content, true)} disabled={content === null}>
              Explain with AI
            </Btn>
            <Btn icon={<Sparkles size={14} />} onClick={() => content !== null && onAskFile(path, content, false)} disabled={content === null}>
              Ask about this file
            </Btn>
          </div>
        </div>
      </Card>

      <Card className="overflow-hidden">
        {loading ? (
          <div className="flex items-center justify-center gap-2 py-16 text-zinc-500">
            <Loader2 size={18} className="animate-spin text-gold-400" /> Loading file…
          </div>
        ) : content === null ? (
          <div className="p-8 text-center">
            <EmptyState
              icon={<FileText size={22} />}
              title="Content unavailable"
              body={
                "This file couldn't be read (binary, too large, or loaded from history without the original source). Re-import the project to read contents — you can still ask the assistant about it."
              }
            />
          </div>
        ) : (
          <>
            <div className="flex items-center justify-between border-b border-white/5 px-4 py-2">
              <span className="text-[11px] text-zinc-500">First {Math.min(400, content.split("\n").length)} of {content.split("\n").length} lines</span>
              <span className="text-[11px] text-zinc-600">{(content.length / 1024).toFixed(1)} KB</span>
            </div>
            <pre className="max-h-[60vh] overflow-auto p-4 font-mono text-[12px] leading-relaxed text-zinc-300">
              {content.split("\n").slice(0, 400).map((l, i) => (
                <div key={i} className="flex">
                  <span className="w-10 shrink-0 select-none pr-3 text-right text-zinc-700">{i + 1}</span>
                  <span className="whitespace-pre-wrap">{l || " "}</span>
                </div>
              ))}
            </pre>
          </>
        )}
      </Card>
    </div>
  );
}

