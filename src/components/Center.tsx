const TABS: Array<{ id: Tab; label: string; icon: React.ReactNode }> = [
  { id: "overview", label: "Overview", icon: <LayoutDashboard size={14} /> },
  { id: "architecture", label: "Architecture", icon: <Network size={14} /> },
  { id: "dependencies", label: "Dependencies", icon: <Boxes size={14} /> },
  { id: "diagram", label: "Diagram", icon: <Workflow size={14} /> },
  { id: "security", label: "Security", icon: <ShieldAlert size={14} /> },
  { id: "quality", label: "Quality", icon: <BarChart3 size={14} /> },
];

export function Center({
  a,
  tab,
  setTab,
  selectedFile,
  readFile,
  onAskFile,
  onGenerate,
  genBusy,
  hasKey,
  onOpenSettings,
}: {
  a: ProjectAnalysis;
  tab: Tab;
  setTab: (t: Tab) => void;
  selectedFile: string | null;
  readFile: (p: string) => Promise<string | null>;
  onAskFile: (path: string, content: string, explain?: boolean) => void;
  onGenerate: (section: "architecture" | "quality" | "readme") => void;
  genBusy: "architecture" | "quality" | "readme" | null;
  hasKey: boolean;
  onOpenSettings: () => void;
}) {
  const tabs = selectedFile ? [...TABS, { id: "file" as Tab, label: "File", icon: <FileText size={14} /> }] : TABS;

  return (
    <main className="flex min-w-0 flex-1 flex-col bg-ink-900">
      <div className="flex shrink-0 items-center gap-1 overflow-x-auto border-b border-white/5 px-4 pt-2.5">
        {tabs.map((t) => (
          <button
            key={t.id}
            onClick={() => setTab(t.id)}
            className={cn(
              "flex items-center gap-1.5 whitespace-nowrap rounded-t-lg border-b-2 px-3.5 py-2.5 text-[13px] font-medium transition-all",
              tab === t.id
                ? "border-gold-400 text-gold-200"
                : "border-transparent text-zinc-500 hover:text-zinc-200"
            )}
          >
            {t.icon}
            {t.label}
            {t.id === "security" && a.security.filter((f) => f.severity === "high").length > 0 && (
              <span className="ml-0.5 flex h-4 min-w-4 items-center justify-center rounded-full bg-red-500/80 px-1 text-[9px] font-bold text-white">
                {a.security.filter((f) => f.severity === "high").length}
              </span>
            )}
          </button>
        ))}
      </div>

      <div className="min-h-0 flex-1 overflow-y-auto p-5">
        {tab === "overview" && <OverviewView a={a} />}
        {tab === "architecture" && (
          <ArchitectureView
            a={a}
            onGenerate={() => onGenerate("architecture")}
            busy={genBusy === "architecture"}
            hasKey={hasKey}
            onOpenSettings={onOpenSettings}
            onGenerateReadme={() => onGenerate("readme")}
            readmeBusy={genBusy === "readme"}
          />
        )}
        {tab === "dependencies" && <DepsView a={a} />}
        {tab === "diagram" && <DiagramView a={a} />}
        {tab === "security" && <SecurityView a={a} />}
        {tab === "quality" && (
          <QualityView
            a={a}
            onGenerate={() => onGenerate("quality")}
            busy={genBusy === "quality"}
            hasKey={hasKey}
            onOpenSettings={onOpenSettings}
          />
        )}
        {tab === "file" && selectedFile && <FileDetailView a={a} path={selectedFile} readFile={readFile} onAskFile={onAskFile} />}
      </div>
    </main>
  );
}
