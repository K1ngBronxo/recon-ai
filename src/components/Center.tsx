const SEV_TONE: Record<SecurityFinding["severity"], "red" | "amber" | "blue" | "gray"> = {
  high: "red",
  medium: "amber",
  low: "blue",
  info: "gray",
};

function SecurityView({ a }: { a: ProjectAnalysis }) {
  const counts = {
    high: a.security.filter((f) => f.severity === "high").length,
    medium: a.security.filter((f) => f.severity === "medium").length,
    low: a.security.filter((f) => f.severity === "low").length,
    info: a.security.filter((f) => f.severity === "info").length,
  };
  return (
    <div className="animate-fadeUp space-y-4">
      <div className="flex items-center gap-2 rounded-xl border border-amber-500/25 bg-amber-500/[0.06] px-4 py-3 text-[12px] leading-relaxed text-amber-100/90">
        <ShieldAlert size={15} className="shrink-0 text-amber-300" />
        <span>
          Heuristic, pattern-based findings only — not a security guarantee. Real secrets should be
          rotated and revoked; always verify findings manually before acting on them.
        </span>
      </div>

      <div className="grid grid-cols-2 gap-3 sm:grid-cols-4">
        <Stat label="High" value={counts.high} icon={<AlertTriangle size={13} />} sub="credentials/secrets" />
        <Stat label="Medium" value={counts.medium} icon={<ShieldAlert size={13} />} sub="config & tokens" />
        <Stat label="Low" value={counts.low} icon={<Info size={13} />} sub="debug & hygiene" />
        <Stat label="Files scanned" value={a.scanStats.filesScanned} icon={<FileText size={13} />} sub={`${fmtBytes(a.scanStats.bytesScanned)} sampled`} />
      </div>

      {a.security.length ? (
        <Card className="divide-y divide-white/5">
          {a.security.map((f, i) => (
            <div key={i} className="flex gap-3 p-4">
              <span className={cn("mt-1.5 h-2 w-2 shrink-0 rounded-full", {
                high: "bg-red-400 shadow-[0_0_8px_rgba(248,113,113,0.6)]",
                medium: "bg-amber-400",
                low: "bg-sky-400",
                info: "bg-zinc-500",
              }[f.severity])} />
              <div className="min-w-0 flex-1">
                <div className="flex flex-wrap items-center gap-2">
                  <Badge tone={SEV_TONE[f.severity]}>{f.severity}</Badge>
                  <Badge>{f.category}</Badge>
                  {f.file && (
                    <span className="font-mono text-[11px] text-zinc-500">
                      {f.file}
                      {f.line ? <span className="text-gold-400">:{f.line}</span> : null}
                    </span>
                  )}
                </div>
                <div className="mt-1 text-[13px] text-zinc-200">{f.message}</div>
                {f.evidence && (
                  <code className="mt-1.5 block truncate rounded-md bg-ink-950/70 px-2 py-1 font-mono text-[11px] text-gold-200/80" title={f.evidence}>
                    {f.evidence}
                  </code>
                )}
              </div>
            </div>
          ))}
        </Card>
      ) : (
        <EmptyState
          icon={<ShieldAlert size={22} />}
          title="No findings"
          body="No obvious secrets, credentials or risky patterns found in the sampled files."
        />
      )}
    </div>
  );
}

